function printAcceptanceRates(nIterationsOuter, ...
                              nIterationsInner1, ...
                              nIterationsInner2, ...
                              acc1, acc2)


tot_its_1 = nIterationsOuter*nIterationsInner1;
tot_its_2 = nIterationsOuter*nIterationsInner2;


disp('Overall acceptance rates')
disp(newline)
T = table( ...
    [round(100*(nnz(acc1==-1)+nnz(acc1==1))/tot_its_1,2); ...
     round(100*nnz(acc2)/tot_its_2,2)], ...
    'VariableNames', {'Acceptance rate (%)'}, ...
    'RowNames', {'Update step 1','Update step 2'});

disp(T)
disp(newline)
disp('Acceptance rates for the two types of edge-shifting')
disp(newline)
T = table( ...
    [round(100*(nnz(acc1==1)+nnz(acc1==2))/tot_its_1,2); ...
     round(100*(nnz(acc1==-1)+nnz(acc1==-2))/tot_its_1,2)], ...
    [round(100*(nnz(acc1==1)/(nnz(acc1==1)+nnz(acc1==2))),2); ...
    round(100*(nnz(acc1==-1)/(nnz(acc1==-1)+nnz(acc1==-2))),2)], ...
    'VariableNames', {'Proposals (%)', 'Acceptance rate (%)'}, ...
    'RowNames', {'Edge-addition','Edge-removal'});
disp(T)
disp(newline)