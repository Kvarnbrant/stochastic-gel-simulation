function nodesInSlice = plotSimulatedNetworkSlice(Nodes, ...
                                                  Edges, ...
                                                  nx,ny,nz, ...
                                                  maxDist, ...
                                                  xMin,xMax, ...
                                                  yMin,yMax, ...
                                                  zMin,zMax)


nodesInSlice = find(Nodes(:,1) >= xMin & Nodes(:,1) <= xMax & ...
                   Nodes(:,2) >= yMin & Nodes(:,2) <= yMax & ...
                   Nodes(:,3) >= zMin & Nodes(:,3) <= zMax);
nodesInSlice = int16(nodesInSlice');

nNodes = size(Nodes,1);
figure
clf
hold on

color1 = [242 173 46]/255;
color2 = [214 103 26]/255;


for i = nodesInSlice
    
    for j = 1:nNodes
       
        if Edges(i,j)
            dist = norm(Nodes(i,:)-Nodes(j,:));
            if dist > maxDist
                newCoords = closestCoordsVec(Nodes(i,:),Nodes(j,:),nx,ny,nz);
                plot3([Nodes(i,1),newCoords(1)], ...
                      [Nodes(i,2),newCoords(2)], ...
                      [Nodes(i,3),newCoords(3)], ...
                      'color',color1, ...
                      'LineWidth',1.2)
            else
                plot3([Nodes(i,1),Nodes(j,1)], ...
                      [Nodes(i,2),Nodes(j,2)], ...
                      [Nodes(i,3),Nodes(j,3)], ...
                      'color',color1, ...
                      'LineWidth',1.2)
            end
        end
    end
end

scatter3(Nodes(nodesInSlice,1), ...
         Nodes(nodesInSlice,2), ...
         Nodes(nodesInSlice,3), ...
         5, ...
         color2, ...
         'filled')


view(3)
axis equal
end
