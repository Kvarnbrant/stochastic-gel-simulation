function prob = getProbabilityAlt1( ...
                        intIdx, ...
                        propTarget, ...
                        c1, ...
                        totalEdges, ...
                        nI, ...
                        nConnections1,nConnections2, ...
                        newAngles,oldAngles, ...
                        degreeTarget,angleTarget, ...
                        c2,c3, ...
                        connected)


f1Old = f1newEnergy(c1,totalEdges,nI,propTarget);


if (isempty(newAngles)) 
    newAngles = angleTarget;
end

if (isempty(oldAngles))
    oldAngles = angleTarget;
end

if connected
    nI(intIdx) = nI(intIdx) - 1;
    f1New = f1newEnergy(c1,totalEdges-1,nI,propTarget);
    delta_f2 = c2*((nConnections1-1-degreeTarget)^2 ...
        + (nConnections2-1-degreeTarget)^2 ...
        - (nConnections1-degreeTarget)^2 ...
        - (nConnections2-degreeTarget)^2);

    delta_f3 = c3*(sum((newAngles-angleTarget).^2) ...
        - sum((oldAngles-angleTarget).^2));

else
    nI(intIdx) = nI(intIdx) + 1;
    f1New = f1newEnergy(c1,totalEdges+1,nI,propTarget);
    delta_f2 = c2*((nConnections1+1-degreeTarget)^2 ...
        + (nConnections2+1-degreeTarget)^2 ...
        - (nConnections1-degreeTarget)^2 ...
        - (nConnections2-degreeTarget)^2);

    delta_f3 = c3*(sum((newAngles-angleTarget).^2) ...
        - sum((oldAngles-angleTarget).^2));
end

delta_f1 = f1New - f1Old;

delta_f = delta_f1 + delta_f2 + delta_f3;

hastings_ratio = exp(-delta_f);

prob = min(hastings_ratio,1);

end

